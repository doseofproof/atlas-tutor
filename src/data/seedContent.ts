let n = 0;
const mc = (
  topicId: string, prompt: string, choices: string[], answerIndex: number, explanation: string, breakdown?: string
): Question => ({
  id: `seed-${topicId}-${n++}`,
  subjectId: 'spanish',
  topicId,
  kind: 'multiple-choice',
  prompt,
  choices,
  answer: choices[answerIndex],
  answerIndex,
  explanation,
  breakdown,
  source: 'seed',
  createdAt: 0,
});

